import { ago } from './time';
import type { Incident } from '../types';

/**
 * 부표 줄에 쓸 <b>한 문장</b>.
 *
 * <p>전에는 `신호 ○ · 사람 ✕` 처럼 축 둘을 따로 찍었다. 처음 보는 사람에게 셋 다 막혔다 —
 * 무엇의 신호인지 안 적혀 있고, <b>`사람 ✕` 가 "사람이 없다"로 읽히고</b>(실제 뜻은
 * "부표 버튼이 안 눌렸다"), ○/✕ 가 있음·없음인지 좋음·나쁨인지 모호했다.</p>
 *
 * <p>무엇보다 진짜 정보는 두 축에 따로 있지 않고 <b>조합</b>에 있다. 조합은 네 가지뿐이고
 * 조합마다 구조가 할 일이 다르다. 그래서 기호 둘 대신 조합의 이름을 찍는다(2026-09-17).</p>
 *
 * <p>색은 <b>신호만</b> 말한다 — 위치가 들어오는 중이면 초록(`ok`), 끊겼거나 부표가 없으면 빨강(`bad`).
 * 정상을 회색으로 뒀더니 "아무 일 없음"이 아니라 <b>"값이 없음"</b>처럼 읽혔다(2026-09-17).</p>
 *
 * <p>색을 두 축의 <b>조합</b>으로 정하던 때는 "2초 전 신호"가 노란색으로 나와, 색과 글자가 다른 말을 했다.
 * 잘 받고 있는데 신호가 이상한 것처럼 읽혔다. 그래서 색은 신호 한 축만 맡고,
 * 사람이 안 잡은 것은 뒤 문장과 그 앞의 <b>⚠</b> 로 말한다(2026-09-18).</p>
 *
 * <p>신호가 끊긴 것은 잡았든 안 잡았든 <b>빨강</b>이다. 지금 어디 있는지를 모르는 상태라
 * 관제가 할 수 있는 일이 추정뿐이고, 그보다 나쁜 소식이 없다(2026-09-17).</p>
 */
export type BuoyTone = 'ok' | 'bad';

export interface BuoyState {
  /**
   * 앞 조각 — <b>부표 신호</b>. 늘 시간이 먼저 온다("2초 전 신호" · "8분 전 신호 끊김").
   * 시간이 앞에 있어야 지금 아는 것이 얼마나 오래된 것인지가 먼저 읽힌다.
   */
  text: string;
  /** 뒤 조각 — <b>사람</b>. 두 축은 늘 함께 나온다. 하나만 있으면 나머지를 모른다는 뜻이 되어 버린다 */
  tail: string | null;
  tone: BuoyTone;
  /**
   * 사람이 부표를 안 잡았나. 뒤 문장 앞에 <b>⚠</b> 를 붙인다 —
   * 색은 신호가 쓰고 있어서, 잡았는지 여부는 글자만으로는 훑을 때 눈에 안 들어온다.
   */
  notHeld: boolean;
  /** hover 로 보는 긴 설명. 왜 그런 상태인지, 그래서 무엇이 불확실한지 */
  why: string;
}

export function buoyState(x: Incident): BuoyState {
  const b = x.map.buoy;

  // 바다에 부표가 없다. 사람 위치를 잡아 줄 물건 자체가 없는 상태다
  if (!b) {
    const why = x.facts.find(([k]) => k === '실패 사유')?.[1] ?? '사유 모름';
    return {
      text: '부표 발사 실패',
      tail: '바다에 부표가 없음',
      tone: 'bad',
      notHeld: false,
      why: `부표 발사에 실패해 바다에 부표가 없습니다 (${why}). 사람 위치는 익수 지점에서 계산한 추정뿐입니다.`,
    };
  }

  const live = b.fix === 'measured';
  const held = b.heldAt !== null;

  if (live && held) {
    return {
      text: `${ago(b.ageSec)} 신호`,
      tail: '사람이 부표를 잡고 있음',
      tone: 'ok',
      notHeld: false,
      why: '부표 버튼이 눌려 있고 위치도 실시간으로 들어옵니다. 부표가 있는 곳에 사람이 있습니다.',
    };
  }

  if (live && !held) {
    return {
      text: `${ago(b.ageSec)} 신호`,
      tail: '사람이 부표를 안 잡음',
      tone: 'ok',
      notHeld: true,
      why: '부표 위치는 받고 있지만 버튼이 눌리지 않았습니다. 못 잡은 것일 수도, 누를 힘이 없는 것일 수도 있습니다.'
        + ' 부표는 바람을 3%, 사람은 1% 타서 시간이 갈수록 둘이 벌어집니다.',
    };
  }

  if (!live && held) {
    return {
      text: `${ago(b.ageSec)} 신호 끊김`,
      tail: '사람이 잡고 있었음',
      tone: 'bad',
      notHeld: false,
      why: `부표 위치가 ${ago(b.ageSec)}부터 들어오지 않습니다. 끊기기 직전까지는 버튼이 눌려 있었지만,`
        + ' 지금도 잡고 있는지는 알 수 없습니다. 지도의 범위는 조류·바람으로 계산한 추정입니다.',
    };
  }

  return {
    text: `${ago(b.ageSec)} 신호 끊김`,
    tail: '사람이 잡은 적 없음',
    tone: 'bad',
    notHeld: true,
    why: `부표 위치가 ${ago(b.ageSec)}부터 들어오지 않고, 버튼도 눌린 적이 없습니다.`
      + ' 지금 지도에 있는 것은 전부 조류·바람으로 계산한 추정입니다.',
  };
}
