import type { Incident } from '../types';

/**
 * 진행 중 사고의 **시계만** 1초 흘려보낸다.
 *
 * <p>서버는 5초에 한 번만 답한다. 그 사이를 이 tick 이 메운다 —
 * 경과 시각이 5초씩 튀면 "실시간으로 보고 있다"가 아니라 "가끔 갱신된다"로 읽힌다.</p>
 *
 * <h3>위치는 여기서 손대지 않는다</h3>
 * <p>예전엔 부표 좌표를 매초 <b>발사 지점 + 경과 × 표류</b> 로 다시 계산해 덮어썼다.
 * 배가 아직 위치를 안 보내던 때 화면이 멈춰 보이지 않게 하려는 장치였다.
 * 지금은 <b>서버가 실제 부표 좌표를 준다</b>(`/api/accidents/&#123;id&#125;/buoy-positions`).
 * 그런데도 계산값으로 덮으면 배가 보낸 진짜 위치가 1초 뒤에 지워진다.
 * 그래서 뺀다(2026-09-20).</p>
 *
 * <p>같은 이유로 두 가지도 뺀다(2026-09-20):
 * <b>신고 횟수</b>는 서버가 준다(reports 의 sentCount 합계). 여기서 7.5초마다 +1 하면
 * 두 번 나간 신고가 화면에선 여덟까지 굴렀다. <b>영상 길이</b>는 서버가 아직 주지 않아
 * 빈 껍데기(길이 0)인데, 그걸 매초 늘렸다 — 한 시간짜리 사고가 "영상 3600초"가 되고
 * 정작 틀어볼 파일은 없다. 영상을 받기 시작하면 그때 다시 생각한다.</p>
 *
 * <p>남은 일은 <b>시간을 세는 것</b>뿐이다. 시간은 지어낸 값이 아니라 실제로 흐른다 —
 * 경과가 늘면 두절이 길어지고, 두절이 길어지면 추정 범위가 넓어진다. 그 연쇄는 진짜다.</p>
 */
export function tick(x: Incident): Incident {
  if (x.state !== 'live') return x;

  const elapsedSec = x.elapsedSec + 1;
  const map = { ...x.map };

  /**
   * 🔴 **이미 끊긴 것만 경과를 늘린다.**
   *
   * 수신 중({@code fix: 'measured'})인데 경과만 늘리면 "실측인데 2분째 안 받았다"가 되어 앞뒤가 안 맞는다.
   * 그렇다고 경과가 길어졌다고 웹이 {@code fix} 를 추정으로 바꿔서도 안 된다 —
   * 통신 두절 판정의 주체가 아직 정해지지 않았고(api.md §9 4), 웹이 끼어들면 판정이 셋이 된다.
   *
   * 두절 중인 부표는 경과가 늘어나는 것이 사실이고, 그 값이 lib/view.ts 에서
   * "마지막 실측 자리에서 얼마나 흘렀나"의 입력이 된다.
   */
  if (map.buoy && map.buoy.fix === 'estimated') {
    map.buoy = { ...map.buoy, ageSec: map.buoy.ageSec + 1 };
  }

  return { ...x, elapsedSec, map };
}
