/** `12:04:18` → 하루 중 초. 못 읽으면 null */
export function secOfClock(at: string | null | undefined): number | null {
  if (!at) return null;
  const m = /^(\d{1,2}):(\d{2}):(\d{2})$/.exec(at);
  if (!m) return null;
  return Number(m[1]) * 3600 + Number(m[2]) * 60 + Number(m[3]);
}
